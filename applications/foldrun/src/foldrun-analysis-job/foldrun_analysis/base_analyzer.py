DEFAULT_GEMINI_DISCLAIMER = (
    "\n\n---\n"
    "*This analysis was generated by AI (Google Gemini) and has not been "
    "peer-reviewed. It is intended as a starting point for interpretation, "
    "not as expert biological advice. Predictions should be validated "
    "experimentally by qualified scientists before use in research or "
    "clinical decisions.*"
)


@dataclass
class SampleMetrics:
    """Normalized per-sample confidence and geometry metrics extracted by a subclass."""

    ranking_score: float | None = None
    ptm: float | None = None
    iptm: float | None = None
    avg_plddt: float | None = None
    gpde: float | None = None
    pae_mean: float | None = None
    pae_max: float | None = None
    has_clash: int | float = 0
    disorder: int | float = 0
    chain_ptm: dict[str, Any] = field(default_factory=dict)
    chain_pair_iptm: dict[str, Any] = field(default_factory=dict)
    plddt_scores: list[float] = field(default_factory=list)
    pde_matrix: list[Any] | None = None
    pae_matrix: list[Any] | None = None


@dataclass
class JobExtras:
    """Model-specific job inputs and auxiliary outputs attached during consolidation."""

    fasta_sequence: str | None = None
    fasta_header: str | None = None
    extra_protein_info: dict[str, Any] = field(default_factory=dict)
    extra_summary_fields: dict[str, Any] = field(default_factory=dict)


class BaseStructureAnalyzer(ABC):
    """Shared execution, plotting, consolidation, and Gemini review pipeline."""

    model_type: ClassVar[str] = ""
    display_name: ClassVar[str] = ""
    extract_plddt_from_cif: ClassVar[bool] = False
    consolidation_settle_seconds: float = 2.0
    gemini_disclaimer: ClassVar[str] = DEFAULT_GEMINI_DISCLAIMER

    @abstractmethod
    def _extract_sample_metrics(
        self,
        pred: dict[str, Any],
        aggregated: dict[str, Any],
        chain_info: list[dict[str, Any]],
        cif_plddt_scores: list[float],
    ) -> SampleMetrics:
        """Extract model-specific confidence metrics, pLDDT array, and PDE matrix."""

    @abstractmethod
    def _load_job_extras(
        self,
        job_metadata: dict[str, Any],
        analysis_path: str,
        task_config: dict[str, Any] | None = None,
        **kwargs: Any,
    ) -> JobExtras:
        """Load model-specific query inputs (JSON/YAML) and extra outputs (e.g. affinity)."""

    @abstractmethod
    def _build_expert_prompt(self, summary_data: dict[str, Any]) -> str:
        """Construct the model-specific Gemini structural biology prompt."""

    def format_common_prompt_sections(
        self,
        summary_data: dict[str, Any],
        *,
        model_label: str | None = None,
        extra_section: str = "",
    ) -> str:
        """Format shared structural summary and confidence tables for Gemini prompts."""
        best = summary_data["best_prediction"]
        summary = summary_data["summary"]
        top_preds = summary_data["top_predictions"][:3]

        chain_desc = ""
        for ci in best.get("chain_info", []):
            if ci["molecule_type"] == "ligand":
                comps = ", ".join(ci.get("comp_ids", [])[:3])
                chain_desc += (
                    f"- Chain {ci['chain_id']}: {ci['molecule_type']} ({comps}), "
                    f"{ci['atom_count']} atoms\n"
                )
            else:
                chain_desc += (
                    f"- Chain {ci['chain_id']}: {ci['molecule_type']}, "
                    f"{ci['residue_count']} residues, {ci['atom_count']} atoms\n"
                )

        gpde_str = (
            f"{best.get('gpde', 0):.4f}" if best.get("gpde") is not None else "N/A"
        )
        rs_str = (
            f"{best['ranking_score']:.4f}"
            if best.get("ranking_score") is not None
            else "N/A"
        )
        ptm_str = f"{best['ptm']:.4f}" if best.get("ptm") is not None else "N/A"
        iptm_str = f"{best['iptm']:.4f}" if best.get("iptm") is not None else "N/A"
        plddt_str = (
            f"{best['plddt_mean']:.2f}" if best.get("plddt_mean") is not None else "N/A"
        )

        model_line = f"- Model: {model_label}\n" if model_label else ""
        prompt = (
            f"**Prediction Summary:**\n"
            f"{model_line}"
            f"- Job ID: {summary_data['job_id']}\n"
            f"- Total Tokens/Residues: {summary['protein_info']['sequence_length']}\n"
            f"- Total Samples: {summary['protein_info']['total_predictions']}\n"
            f"- Best Sample: {best['sample_name']} (Rank #{best.get('rank', 1)})\n\n"
            f"**Chain Composition:**\n"
            f"{chain_desc}"
            f"**Quality Metrics (Best Sample):**\n"
            f"- Ranking Score: {rs_str}\n"
            f"- pTM: {ptm_str}\n"
            f"- ipTM: {iptm_str}\n"
            f"- Mean pLDDT: {plddt_str}\n"
            f"- GPDE: {gpde_str}\n"
            f"- Has Clash: {'Yes' if best.get('has_clash') else 'No'}\n"
            f"- Disorder: {'Yes' if best.get('disorder') else 'No'}\n"
        )

        if best.get("chain_ptm"):
            prompt += "\n**Per-Chain pTM:**\n"
            for chain, score in best["chain_ptm"].items():
                score_s = f"{score:.4f}" if score is not None else "N/A"
                prompt += f"- Chain {chain}: {score_s}\n"

        if best.get("chain_pair_iptm"):
            prompt += "\n**Chain-Pair ipTM (interface quality):**\n"
            for pair, score in best["chain_pair_iptm"].items():
                score_s = f"{score:.4f}" if score is not None else "N/A"
                prompt += f"- {pair}: {score_s}\n"

        if best.get("per_chain_plddt"):
            prompt += "\n**Per-Chain pLDDT (protein vs ligand breakdown):**\n"
            for cid, stats in best["per_chain_plddt"].items():
                mol_type = stats.get("molecule_type", "unknown")
                comps = ", ".join(stats.get("comp_ids", [])[:3])
                comp_str = f" ({comps})" if mol_type == "ligand" else ""
                mean_s = (
                    f"{stats['mean']:.1f}" if stats.get("mean") is not None else "N/A"
                )
                min_s = f"{stats['min']:.1f}" if stats.get("min") is not None else "N/A"
                max_s = f"{stats['max']:.1f}" if stats.get("max") is not None else "N/A"
                prompt += (
                    f"- Chain {cid} ({mol_type}{comp_str}): "
                    f"mean pLDDT={mean_s}, "
                    f"range=[{min_s}, {max_s}], "
                    f"{stats['atom_count']} atoms\n"
                )

        prompt += "\n**Confidence Distribution (Best Sample):**\n"
        if best.get("plddt_distribution"):
            dist = best["plddt_distribution"]
            prompt += (
                f"- Very High (90-100): {dist.get('very_high_confidence', 0)} atoms\n"
            )
            prompt += f"- High (70-90): {dist.get('high_confidence', 0)} atoms\n"
            prompt += f"- Low (50-70): {dist.get('low_confidence', 0)} atoms\n"
            prompt += f"- Very Low (<50): {dist.get('very_low_confidence', 0)} atoms\n"

        all_preds = summary_data.get("all_predictions_summary", [])
        if len(all_preds) > 1:
            all_scores = [
                p["ranking_score"]
                for p in all_preds
                if p.get("ranking_score") is not None
            ]
            if all_scores:
                prompt += f"\n**Sample Diversity (all {len(all_preds)} samples):**\n"
                prompt += (
                    f"- Ranking score range: {min(all_scores):.4f} - "
                    f"{max(all_scores):.4f} "
                    f"(spread: {max(all_scores) - min(all_scores):.4f})\n"
                )
                prompt += (
                    f"- Mean ranking score: {sum(all_scores) / len(all_scores):.4f}\n"
                )

        prompt += "\n**Top 3 Samples Comparison:**\n"
        for i, pred in enumerate(top_preds, 1):
            clash_str = " [CLASH]" if pred.get("has_clash") else ""
            p_rs = (
                f"{pred['ranking_score']:.4f}"
                if pred.get("ranking_score") is not None
                else "N/A"
            )
            p_ptm = f"{pred['ptm']:.4f}" if pred.get("ptm") is not None else "N/A"
            p_iptm = f"{pred['iptm']:.4f}" if pred.get("iptm") is not None else "N/A"
            prompt += (
                f"{i}. {pred['sample_name']}: ranking_score {p_rs}, "
                f"pTM {p_ptm}, ipTM {p_iptm}{clash_str}\n"
            )

        if extra_section:
            prompt += extra_section

        if summary["protein_info"].get("fasta_sequence"):
            fasta_seq = summary["protein_info"]["fasta_sequence"]
            fasta_header = summary["protein_info"].get("fasta_header", "Unknown")
            prompt += f"\n**Input Sequence:**\n>{fasta_header}\n{fasta_seq}\n"

        return prompt

    def generate_gemini_expert_analysis(
        self, summary_data: dict[str, Any]
    ) -> dict[str, Any]:
        """Generate multimodal expert analysis using Gemini via Google GenAI SDK."""
        try:
            best = summary_data["best_prediction"]
            prompt = self._build_expert_prompt(summary_data)

            logger.info(
                f"Generating Gemini expert analysis for {self.display_name or self.model_type}..."
            )
            content_parts: list[Any] = [prompt]

            plots = best.get("plots") or {}
            plot_specs = (
                ("plddt_plot", "pLDDT Plot (Best Sample):"),
                ("pae_plot", "PAE Plot (Best Sample):"),
                ("pde_plot", "PDE Plot (Best Sample):"),
                ("iptm_matrix_plot", "ipTM Matrix (Best Sample):"),
            )
            for plot_key, label in plot_specs:
                img_uri = plots.get(plot_key)
                if img_uri:
                    try:
                        content_parts.append(f"\n\n**{label}**")
                        content_parts.append(
                            types.Part.from_uri(file_uri=img_uri, mime_type="image/png")
                        )
                    except Exception as exc:
                        logger.warning(f"Could not include {plot_key}: {exc}")

            gemini_model = os.getenv("GEMINI_MODEL", "gemini-4-argon")
            with genai.Client() as client:
                response = client.models.generate_content(
                    model=gemini_model,
                    contents=content_parts,
                    config=types.GenerateContentConfig(temperature=1.0),
                )

            return {
                "status": "success",
                "analysis": (response.text or "") + self.gemini_disclaimer,
                "model": gemini_model,
                "generated_at": datetime.now(UTC).replace(tzinfo=None).isoformat()
                + "Z",
                "ai_generated": True,
            }
        except Exception as exc:
            logger.error(f"Error generating Gemini analysis: {exc}", exc_info=True)
            return {"status": "error", "error": str(exc)}

    @staticmethod
    def _render_and_upload_plot(
        plot_uri: str,
        render_fn: Callable[[str], None],
    ) -> str | None:
        """Render a plot to a temporary PNG file, upload to GCS, and clean up."""
        return shared_utils.render_and_upload_plot(plot_uri, render_fn)

    def analyze_sample(self, pred_idx: int, pred: dict[str, Any]) -> dict[str, Any]:
        """Analyze a single predicted sample, render plots, and return validated dict."""
        sample_name = pred["sample_name"]
        cif_uri = pred["cif_uri"]
        confidences_uri = pred.get("confidences_uri", "")
        aggregated_uri = pred.get("aggregated_uri") or confidences_uri
        output_uri = pred["output_uri"]

        logger.info(
            f"Starting {self.display_name or self.model_type} analysis for sample: "
            f"{sample_name} (index {pred_idx})"
        )

        aggregated = shared_utils.download_json_from_gcs(aggregated_uri)
        chain_info: list[dict[str, Any]] = []
        cif_plddt_scores: list[float] = []
        try:
            cif_text = shared_utils.download_text_from_gcs(cif_uri)
            chain_info, cif_plddt_scores = shared_utils.parse_cif_chains(
                cif_text, extract_plddt=self.extract_plddt_from_cif
            )
        except Exception as exc:
            logger.warning(f"Could not parse CIF: {exc}")

        metrics = self._extract_sample_metrics(
            pred=pred,
            aggregated=aggregated,
            chain_info=chain_info,
            cif_plddt_scores=cif_plddt_scores,
        )

        plddt_stats = shared_utils.calculate_plddt_stats(metrics.plddt_scores)
        if plddt_stats["mean"] is None and metrics.avg_plddt is not None:
            plddt_stats["mean"] = metrics.avg_plddt
            plddt_stats["median"] = metrics.avg_plddt

        per_chain_plddt: dict[str, Any] = {}
        if metrics.plddt_scores and chain_info:
            per_chain_plddt = shared_utils.calculate_per_chain_plddt(
                metrics.plddt_scores, chain_info
            )

        quality = shared_utils.get_quality_assessment(plddt_stats["mean"])

        plot_files: dict[str, str] = {}
        output_base = output_uri.rsplit("/", 1)[0]

        plddt_scores = metrics.plddt_scores
        if plddt_scores:
            plddt_plot_uri = self._render_and_upload_plot(
                f"{output_base}/plddt_plot_{pred_idx}.png",
                lambda path: shared_utils.plot_plddt_distribution(
                    plddt_scores, sample_name, path, chain_info
                ),
            )
            if plddt_plot_uri:
                plot_files["plddt_plot"] = plddt_plot_uri

        pae_matrix = metrics.pae_matrix
        if pae_matrix:
            pae_plot_uri = self._render_and_upload_plot(
                f"{output_base}/pae_plot_{pred_idx}.png",
                lambda path: shared_utils.plot_error_matrix(
                    pae_matrix,
                    sample_name,
                    "Predicted Aligned Error (Å)",
                    path,
                    chain_info,
                ),
            )
            if pae_plot_uri:
                plot_files["pae_plot"] = pae_plot_uri

        pde_matrix = metrics.pde_matrix
        if pde_matrix:
            pde_plot_uri = self._render_and_upload_plot(
                f"{output_base}/pde_plot_{pred_idx}.png",
                lambda path: shared_utils.plot_error_matrix(
                    pde_matrix,
                    sample_name,
                    "Predicted Distance Error (Å)",
                    path,
                    chain_info,
                ),
            )
            if pde_plot_uri:
                plot_files["pde_plot"] = pde_plot_uri

        chain_pair_iptm = metrics.chain_pair_iptm
        if chain_pair_iptm and len(chain_info) > 1:
            iptm_plot_uri = self._render_and_upload_plot(
                f"{output_base}/iptm_matrix_{pred_idx}.png",
                lambda path: shared_utils.plot_iptm_matrix(
                    chain_pair_iptm,
                    sample_name,
                    path,
                    metrics.chain_ptm,
                    chain_info,
                ),
            )
            if iptm_plot_uri:
                plot_files["iptm_matrix_plot"] = iptm_plot_uri

        analysis: dict[str, Any] = {
            "prediction_index": pred_idx,
            "sample_name": sample_name,
            "rank": pred_idx + 1,
            "ranking_score": metrics.ranking_score,
            "ptm": metrics.ptm,
            "iptm": metrics.iptm,
            "avg_plddt": metrics.avg_plddt,
            "gpde": metrics.gpde,
            "pae_mean": metrics.pae_mean,
            "pae_max": metrics.pae_max,
            "has_clash": metrics.has_clash,
            "disorder": metrics.disorder,
            "chain_ptm": metrics.chain_ptm,
            "chain_pair_iptm": metrics.chain_pair_iptm,
            "per_chain_plddt": per_chain_plddt,
            "chain_info": chain_info,
            "plddt_mean": plddt_stats["mean"],
            "plddt_median": plddt_stats["median"],
            "plddt_min": plddt_stats["min"],
            "plddt_max": plddt_stats["max"],
            "plddt_std": plddt_stats["std"],
            "plddt_distribution": plddt_stats["distribution"],
            "plddt_scores": plddt_stats["per_residue"],
            "quality_assessment": quality,
            "has_pde": metrics.pde_matrix is not None,
            "has_pae": metrics.pae_matrix is not None,
            "cif_uri": cif_uri,
            "aggregated_uri": aggregated_uri,
            "confidences_uri": confidences_uri,
            "analyzed_at": datetime.now(UTC).replace(tzinfo=None).isoformat() + "Z",
            "plots": plot_files,
        }
        SampleAnalysisResult.model_validate(analysis)
        return analysis

    def consolidate_results(
        self,
        job_id: str,
        analysis_path: str,
        bucket_name: str,
        task_count: int,
        task_config: dict[str, Any] | None = None,
        **extra_kwargs: Any,
    ) -> dict[str, Any] | None:
        """Consolidate per-sample analysis JSONs into ``summary.json`` and ZIP bundle."""
        logger.info(
            f"Consolidating {self.display_name or self.model_type} results from {analysis_path}"
        )
        if self.consolidation_settle_seconds > 0:
            time.sleep(self.consolidation_settle_seconds)

        if not analysis_path.endswith("/"):
            analysis_path += "/"

        parts = analysis_path[5:].split("/", 1)
        prefix = parts[1] if len(parts) > 1 else ""
        if prefix and not prefix.endswith("/"):
            prefix += "/"
        if prefix.startswith("/"):
            prefix = prefix[1:]

        storage_client = shared_utils.storage.Client()
        bucket = storage_client.bucket(bucket_name)

        blobs = bucket.list_blobs(prefix=prefix)
        completed_files = [
            f"gs://{bucket_name}/{blob.name}"
            for blob in blobs
            if "prediction_" in blob.name and blob.name.endswith("_analysis.json")
        ]
        logger.info(f"Found {len(completed_files)} analysis files to consolidate")

        all_analyses: list[dict[str, Any]] = []
        for file_path in completed_files:
            try:
                analysis = shared_utils.download_json_from_gcs(file_path)
                all_analyses.append(analysis)
            except Exception as exc:
                logger.error(f"Failed to read {file_path}: {exc}")

        if not all_analyses:
            logger.error("No analyses found to consolidate")
            return None

        job_metadata = shared_utils.get_job_metadata(job_id)
        extras = self._load_job_extras(
            job_metadata=job_metadata,
            analysis_path=analysis_path,
            task_config=task_config,
            **extra_kwargs,
        )

        all_analyses.sort(
            key=lambda x: (
                x.get("ranking_score") is not None,
                x["ranking_score"] if x.get("ranking_score") is not None else -1e9,
                x.get("plddt_mean") is not None,
                x["plddt_mean"] if x.get("plddt_mean") is not None else -1e9,
            ),
            reverse=True,
        )

        for i, analysis in enumerate(all_analyses):
            analysis["rank"] = i + 1

        best = all_analyses[0]
        ranking_scores = [
            a["ranking_score"]
            for a in all_analyses
            if a.get("ranking_score") is not None
        ]
        plddt_means = [
            a["plddt_mean"] for a in all_analyses if a.get("plddt_mean") is not None
        ]

        chain_composition: list[dict[str, Any]] = []
        best_chain_info = best.get("chain_info", [])
        total_residues = 0
        for ci in best_chain_info:
            total_residues += ci["residue_count"]
            entry: dict[str, Any] = {
                "chain_id": ci["chain_id"],
                "molecule_type": ci["molecule_type"],
                "residue_count": ci["residue_count"],
                "atom_count": ci["atom_count"],
            }
            if ci["molecule_type"] == "ligand":
                entry["comp_ids"] = ci.get("comp_ids", [])
            chain_composition.append(entry)

        protein_info: dict[str, Any] = {
            "sequence_length": total_residues
            if total_residues > 0
            else len(best.get("plddt_scores", [])),
            "total_predictions": len(all_analyses),
            "fasta_sequence": extras.fasta_sequence,
            "fasta_header": extras.fasta_header,
            "job_metadata": job_metadata,
            "model_type": self.model_type,
            "chain_composition": chain_composition,
            **extras.extra_protein_info,
        }

        summary: dict[str, Any] = {
            "protein_info": protein_info,
            "quality_metrics": {
                "best_ranking_score": best["ranking_score"],
                "best_ptm": best["ptm"],
                "best_iptm": best["iptm"],
                "best_plddt": best["plddt_mean"],
                "best_model_pae": best.get("pae_mean"),
                "quality_assessment": best["quality_assessment"],
            },
            **extras.extra_summary_fields,
            "statistics": {
                "total_predictions": len(all_analyses),
                "analyzed_successfully": len(all_analyses),
                "ranking_score_stats": {
                    "mean": sum(ranking_scores) / len(ranking_scores)
                    if ranking_scores
                    else None,
                    "min": min(ranking_scores) if ranking_scores else None,
                    "max": max(ranking_scores) if ranking_scores else None,
                    "range": max(ranking_scores) - min(ranking_scores)
                    if ranking_scores
                    else None,
                },
                "plddt_stats": {
                    "mean": sum(plddt_means) / len(plddt_means)
                    if plddt_means
                    else None,
                    "min": min(plddt_means) if plddt_means else None,
                    "max": max(plddt_means) if plddt_means else None,
                    "range": max(plddt_means) - min(plddt_means)
                    if plddt_means
                    else None,
                },
            },
        }

        summary_data: dict[str, Any] = {
            "job_id": job_id,
            "model_type": self.model_type,
            "analyzed_at": datetime.now(UTC).replace(tzinfo=None).isoformat() + "Z",
            "total_predictions": len(all_analyses),
            "summary": summary,
            "best_prediction": best,
            "top_predictions": all_analyses[:10],
            "all_predictions_summary": [
                {
                    "rank": a["rank"],
                    "sample_name": a["sample_name"],
                    "ranking_score": a["ranking_score"],
                    "ptm": a["ptm"],
                    "iptm": a["iptm"],
                    "plddt_mean": a["plddt_mean"],
                    "plddt_min": a["plddt_min"],
                    "pae_mean": a.get("pae_mean"),
                    "quality_assessment": a["quality_assessment"],
                    "has_clash": a.get("has_clash", 0),
                    "per_chain_plddt": a.get("per_chain_plddt", {}),
                    "chain_info": a.get("chain_info", []),
                    "cif_uri": a["cif_uri"],
                    "plots": a.get("plots", {}),
                }
                for a in all_analyses
            ],
        }
        if extras.extra_summary_fields.get("affinity") is not None:
            summary_data["affinity"] = extras.extra_summary_fields["affinity"]

        expert_analysis = self.generate_gemini_expert_analysis(summary_data)
        summary_data["expert_analysis"] = expert_analysis

        try:
            archive_meta = shared_utils.build_and_upload_run_archive(
                analysis_path=analysis_path,
                bucket_name=bucket_name,
                summary_data=summary_data,
            )
            summary_data.update(archive_meta)
        except Exception as exc:
            logger.warning(f"Could not build run archive bundle: {exc}")

        AnalysisSummary.model_validate(summary_data)
        summary_uri = f"{analysis_path}summary.json"
        summary_data = shared_utils.upload_json_to_gcs(
            summary_data,
            summary_uri,
            prefix="foldrun_summary_",
        )

        logger.info(f"Consolidation complete! Summary written to {summary_uri}")
        return summary_data

    def run_task(
        self,
        task_index: int,
        task_count: int,
        task_config: dict[str, Any],
        bucket_name: str,
        analysis_path: str,
    ) -> None:
        """Execute strided Cloud Run Job predictions analysis task."""
        validated_config = AnalysisTaskConfig.model_validate(task_config)
        predictions = validated_config.predictions
        total_predictions = len(predictions)
        if task_index >= total_predictions:
            logger.error(f"Task index {task_index} out of range")
            sys.exit(1)

        job_id = validated_config.job_id
        stride = max(1, task_count)
        assigned_indices = list(range(task_index, total_predictions, stride))

        try:
            for pred_idx in assigned_indices:
                pred = predictions[pred_idx]
                output_uri = pred["output_uri"]
                shared_utils.upload_json_to_gcs(
                    self.analyze_sample(pred_idx, pred),
                    output_uri,
                    prefix=f"foldrun_sample_{pred_idx}_",
                )

            consolidator_task_index = min(stride, total_predictions) - 1
            if task_index == consolidator_task_index:
                shared_utils.wait_for_sibling_tasks(
                    bucket_name, analysis_path, total_predictions
                )
                self.consolidate_results(
                    job_id=job_id,
                    analysis_path=analysis_path,
                    bucket_name=bucket_name,
                    task_count=total_predictions,
                    task_config=task_config,
                )
        except Exception as exc:
            logger.error(
                f"Error running {self.display_name or self.model_type} analysis task: {exc}",
                exc_info=True,
            )
            raise
