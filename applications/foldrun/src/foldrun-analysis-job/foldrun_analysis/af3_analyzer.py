def _extract_residue_plddts_from_cif(cif_text: str) -> list[float]:
    """Extract per-residue mean pLDDT values from AlphaFold 3 mmCIF atom_site records."""
    atom_lines = []
    for line in cif_text.splitlines():
        if line.startswith(("ATOM ", "HETATM ")):
            parts = line.split()
            if len(parts) >= 15:
                chain_id = parts[6]
                res_seq = parts[8]
                try:
                    bfac = float(parts[14])
                except (ValueError, IndexError):
                    bfac = None
                atom_lines.append((chain_id, res_seq, bfac))

    if not atom_lines:
        return []

    res_scores: dict[tuple[str, str], list[float]] = {}
    res_order: list[tuple[str, str]] = []
    for chain_id, res_seq, bfac in atom_lines:
        if bfac is None or not np.isfinite(bfac):
            continue
        key = (chain_id, res_seq)
        if key not in res_scores:
            res_scores[key] = []
            res_order.append(key)
        res_scores[key].append(bfac)

    return [float(np.mean(res_scores[k])) for k in res_order]


def _compute_af3_ranking_score(summary_conf: dict) -> float:
    """Compute or extract the AlphaFold 3 ranking score."""
    ranking_score = summary_conf.get("ranking_score")
    if ranking_score is None:
        ptm_val = summary_conf.get("ptm")
        iptm_val = summary_conf.get("iptm")
        frac_dis = float(summary_conf.get("fraction_disordered", 0.0) or 0.0)
        has_clash_val = float(summary_conf.get("has_clash", 0.0) or 0.0)
        if ptm_val is not None:
            eff_iptm = float(iptm_val) if iptm_val is not None else float(ptm_val)
            ranking_score = (
                0.8 * eff_iptm
                + 0.2 * float(ptm_val)
                + 0.5 * frac_dis
                - 100.0 * has_clash_val
            )
        else:
            ranking_score = 0.0
    return round(float(ranking_score), 4)


